    public function seedForOwner(int $ownerId): void
    {
        DB::transaction(function () use ($ownerId) {
            foreach ($this->defaultOptionTypes() as $typeSlug => $defaults) {
                $optionType = OptionType::query()
                    ->whereNull('user_id')
                    ->where('slug', $typeSlug)
                    ->first();

                if (! $optionType) {
                    $optionType = OptionType::create([
                        'user_id' => null,
                        'slug' => $typeSlug,
                        'Name' => $defaults['name'],
                        'type' => $defaults['type'],
                    ]);
                }

                foreach (array_unique($defaults['choices']) as $choice) {
                    Options::firstOrCreate(
                        [
                            'user_id' => $ownerId,
                            'option_id' => $optionType->id,
                            'Name' => $choice,
                        ],
                        [
                            'slug' => 'default-'.$ownerId.'-'.substr(sha1($typeSlug.'|'.$choice), 0, 16),
                        ]
                    );
                }
            }
        });
    }

