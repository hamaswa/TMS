    public function seedForAllTailoringOwners(): void
    {
        $ownerIds = User::query()
            ->where('tailoring_access', true)
            ->where(function ($query) {
                $query->where('is_business_owner', true)
                    ->orWhereHas('roles', fn ($roles) => $roles->where('name', 'shop_owner'));
            })
            ->pluck('id')
            ->merge(Business::query()->where('tailoring_enabled', true)->pluck('owner_user_id'))
            ->filter()
            ->unique();

        foreach ($ownerIds as $ownerId) {
            $this->seedForOwner((int) $ownerId);
        }
    }
